"""Check the complete on-disk fixture through LeRobot #5388 and a PyTorch DataLoader."""

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from lerobot.datasets import streaming_dataset, video_utils
from torch.utils.data import DataLoader


def source_hash(module):
    with Path(module.__file__).open("rb") as source:
        return hashlib.file_digest(source, "sha256").hexdigest()


def oracle_frames(root, dataset):
    out = {}
    for key in dataset.meta.video_keys:
        height, width, channels = dataset.meta.features[key]["shape"]
        for path in sorted((root / "videos" / key).glob("*/*.mp4")):
            decoded = subprocess.check_output(
                [
                    "ffmpeg",
                    "-nostdin",
                    "-v",
                    "error",
                    "-threads",
                    "1",
                    "-i",
                    str(path),
                    "-map",
                    "0:v:0",
                    "-an",
                    "-pix_fmt",
                    "rgb24",
                    "-c:v",
                    "rawvideo",
                    "-threads",
                    "1",
                    "-f",
                    "rawvideo",
                    "pipe:1",
                ]
            )
            frames = np.frombuffer(decoded, dtype=np.uint8).reshape(
                -1, height, width, channels
            )
            out[path.relative_to(root)] = frames.transpose(0, 3, 1, 2)
    return out


def field_hash(value):
    if isinstance(value, torch.Tensor):
        array = value.detach().cpu().contiguous().numpy()
        return {
            "dtype": str(array.dtype),
            "shape": list(array.shape),
            "sha256": hashlib.sha256(array.tobytes()).hexdigest(),
        }
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "root", type=Path, help="Dataset directory generated by fixture.py"
    )
    parser.add_argument("output", type=Path)
    parser.add_argument("--workers", type=int, default=0)
    parser.add_argument(
        "--float", action="store_true", help="Return float32 images in [0, 1]"
    )
    parser.add_argument(
        "--history", action="store_true", help="Request three frames per camera"
    )
    parser.add_argument(
        "--ffmpeg", action="store_true", help="Compare each current image with FFmpeg"
    )
    parser.add_argument("--reference", type=Path, help="Check parity with a prior run")
    args = parser.parse_args()
    if args.history and args.ffmpeg:
        parser.error("--ffmpeg applies to current-frame runs")
    root = args.root.resolve()
    cameras = [
        f"observation.images.{name}" for name in ("front", "left_wrist", "right_wrist")
    ]
    delta_timestamps = (
        {key: [-2 / 25, -1 / 25, 0] for key in cameras} if args.history else None
    )
    # Passing the absolute path as repo_id directs the stock reader to local Parquet.
    ds = streaming_dataset.StreamingLeRobotDataset(
        str(root),
        root=root,
        buffer_size=2,
        return_uint8=not args.float,
        delta_timestamps=delta_timestamps,
    )
    rows = pd.concat(
        pd.read_parquet(file) for file in sorted((root / "data").glob("*/*.parquet"))
    )
    rows = rows.set_index("index", drop=False)
    assert rows.index.is_unique
    ffmpeg = oracle_frames(root, ds) if args.ffmpeg else {}
    torch.set_num_threads(1)
    records = []
    mismatched_images = 0
    checked_images = 0
    max_pixel_difference = 0.0
    batch_sizes = []
    loader = DataLoader(ds, batch_size=19, num_workers=args.workers)
    for batch in loader:
        batch_sizes.append(len(batch["index"]))
        for i in range(len(batch["index"])):
            idx = int(batch["index"][i])
            row = rows.loc[idx]
            ep = int(row.episode_index)
            for name, expected in row.items():
                actual = batch[name][i]
                if isinstance(expected, np.ndarray):
                    if not np.array_equal(actual.numpy(), expected):
                        raise AssertionError((idx, name, actual, expected))
                elif actual.item() != expected:
                    raise AssertionError((idx, name, actual, expected))
            assert batch["task"][i] == ds.meta.tasks.iloc[int(row.task_index)].name
            if args.ffmpeg:
                for key in ds.meta.video_keys:
                    path = ds.meta.get_video_file_path(ep, key)
                    offset = ds.meta.episodes[ep][f"videos/{key}/from_timestamp"]
                    frame_idx = int(round(float(offset) * ds.fps)) + int(
                        row.frame_index
                    )
                    expected = ffmpeg[path][frame_idx]
                    actual = batch[key][i].numpy()
                    expected = (
                        expected.astype(np.float32) / 255 if args.float else expected
                    )
                    checked_images += 1
                    if not np.array_equal(expected, actual):
                        mismatched_images += 1
                        maximum = np.abs(
                            expected.astype(np.float32) - actual.astype(np.float32)
                        ).max()
                        max_pixel_difference = max(max_pixel_difference, float(maximum))
            records.append(
                {
                    "index": idx,
                    "fields": {
                        key: field_hash(value[i])
                        for key, value in sorted(batch.items())
                    },
                }
            )
    assert sorted(record["index"] for record in records) == sorted(rows.index)
    summary = {
        "workers": args.workers,
        "return_uint8": not args.float,
        "camera_history": args.history,
        "records": len(records),
        "loader_batch_sizes": batch_sizes,
        "sha256": hashlib.sha256(
            json.dumps(records, sort_keys=True).encode()
        ).hexdigest(),
        "ffmpeg_rgb_frames_checked": checked_images,
        "mismatched_images": mismatched_images,
        "max_pixel_difference": max_pixel_difference if args.ffmpeg else None,
    }
    if mismatched_images:
        raise AssertionError(f"FFmpeg images differ: {summary}")
    if args.reference is not None:
        reference = json.loads(args.reference.read_text(encoding="utf-8"))
        if summary != reference["summary"]:
            raise AssertionError(f"Reader output differs from the reference: {summary}")
    result = {
        "streaming_source_sha256": source_hash(streaming_dataset),
        "video_utils_source_sha256": source_hash(video_utils),
        "summary": summary,
    }
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
