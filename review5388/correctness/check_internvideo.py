"""Compare every finite fixture batch across the InternVideo2 benchmark arms."""

import argparse
import json
from collections import Counter
from hashlib import file_digest
from itertools import zip_longest
from pathlib import Path
from threading import Lock
from unittest.mock import patch

import torch
from check_stream import Oracle
from lerobot.datasets import streaming_dataset
from torch.utils.data import DataLoader

import internvideo_variants as variants

BATCH_SIZE = 8
DECODER_CACHE_SIZE = 32
ARMS = ("reuse", "batch_singletons", "grouped")


def source_sha256(module):
    with Path(module.__file__).open("rb") as stream:
        return file_digest(stream, "sha256").hexdigest()


def make_loader(root, arm):
    dataset_class = streaming_dataset.StreamingLeRobotDataset
    if arm != "stock":
        dataset_class = variants.make_candidate_variant(
            dataset_class, arm, batch_size=BATCH_SIZE, decoder_cache_size=DECODER_CACHE_SIZE
        )
    dataset = dataset_class(
        str(root), root=root, return_uint8=True, delta_timestamps=None, tolerance_s=0.001, buffer_size=32, seed=42
    )
    return dataset, DataLoader(dataset, batch_size=BATCH_SIZE, num_workers=0)


def check(root):
    torch.set_num_threads(1)
    _, stock = make_loader(root, "stock")
    reference = list(stock)
    oracle = Oracle(root, "anchors", None)
    ids = [
        oracle.sample({field: values[index] for field, values in batch.items()})
        for batch in reference
        for index in range(len(batch["index"]))
    ]
    if sorted(ids) != oracle.ids or oracle.errors:
        raise ValueError(f"Stock output differs from the fixture: {oracle.examples!r}")

    result = {
        "stock_streaming_source_sha256": source_sha256(streaming_dataset),
        "decode_variants_source_sha256": source_sha256(variants),
        "batches": len(reference),
        "anchors": len(ids),
        "final_batch_anchors": len(reference[-1]["index"]),
        "stock_vs_ffmpeg_oracle_max_rgb8_difference": oracle.max_pixel_error,
        "variants": {},
    }
    lock = Lock()
    requests_by_group_size = Counter()
    read_video = variants._read_video

    def observe(pool, path, requests, *args, **kwargs):
        with lock:
            requests_by_group_size[len(requests)] += 1
        return read_video(pool, path, requests, *args, **kwargs)

    with patch.object(variants, "_read_video", observe):
        for arm in ARMS:
            requests_by_group_size.clear()
            _, loader = make_loader(root, arm)
            for number, (expected, actual) in enumerate(zip_longest(reference, loader), 1):
                if expected is None or actual is None or expected.keys() != actual.keys():
                    raise ValueError(f"{arm} batch {number} has a different schema or is missing")
                for field, want in expected.items():
                    got = actual[field]
                    if isinstance(want, torch.Tensor):
                        equal = (
                            isinstance(got, torch.Tensor)
                            and want.dtype == got.dtype
                            and want.shape == got.shape
                            and torch.equal(want, got)
                        )
                    else:
                        equal = want == got
                    if not equal:
                        raise ValueError(f"{arm} batch {number} differs from stock in {field}")
            result["variants"][arm] = {
                "exact_match_to_stock_for_all_fields": True,
                "path_request_groups_by_size": dict(sorted(requests_by_group_size.items())),
            }
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True, help="Fixture generated by fixture.py")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    args.out.write_text(json.dumps(check(args.root.resolve()), indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
